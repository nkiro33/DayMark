import '../models/models.dart';

class PresavedActivityTemplate {
  const PresavedActivityTemplate({
    required this.id,
    required this.title,
    required this.description,
    required this.categoryId,
    required this.iconName,
    required this.activityType,
    required this.trackingType,
    required this.frequency,
    this.daysOfWeek = const [],
    this.expectedDurationMinutes,
    this.baseCredit = 0,
    this.creditPerMinute = 0,
    this.creditPerUnit = 0,
    this.maxDailyCredit,
    this.penaltyCredit = 0,
    this.tags = const [],
  });

  final String id;
  final String title;
  final String description;
  final String categoryId;
  final String iconName;
  final ActivityType activityType;
  final TrackingType trackingType;
  final ScheduleFrequency frequency;
  final List<int> daysOfWeek;
  final int? expectedDurationMinutes;
  final double baseCredit;
  final double creditPerMinute;
  final double creditPerUnit;
  final double? maxDailyCredit;
  final double penaltyCredit;
  final List<String> tags;

  ActivityScope get activityScope {
    return frequency == ScheduleFrequency.manual
        ? ActivityScope.manual
        : ActivityScope.recurring;
  }
}

